// Command contracts generates frontend types and JSON Schemas from server DTOs.
package main

import (
	"encoding/json"
	"flag"
	"fmt"
	"os"
	"reflect"
	"sort"
	"strings"
	"time"

	"github.com/abandon1a2b/ohyeah/internal/app"
	"github.com/abandon1a2b/ohyeah/internal/config"
	"github.com/abandon1a2b/ohyeah/internal/model"
	"github.com/abandon1a2b/ohyeah/internal/registry"
	"github.com/abandon1a2b/ohyeah/internal/store"
	"github.com/abandon1a2b/ohyeah/internal/syncer"
	"github.com/abandon1a2b/ohyeah/pkg/collector"
)

var types = map[reflect.Type]string{}
var schemas = map[string]any{}
var declarations = map[string]string{}
var timeType = reflect.TypeOf(time.Time{})
var rawType = reflect.TypeOf(json.RawMessage{})

func describe(t reflect.Type) (string, any) {
	if t == timeType {
		return "string", map[string]any{"type": "string", "format": "date-time"}
	}
	if t == rawType {
		return "unknown", map[string]any{}
	}
	if t.Kind() == reflect.Pointer {
		ts, schema := describe(t.Elem())
		return ts + " | null", map[string]any{"anyOf": []any{schema, map[string]any{"type": "null"}}}
	}
	switch t.Kind() {
	case reflect.String:
		return "string", map[string]any{"type": "string"}
	case reflect.Bool:
		return "boolean", map[string]any{"type": "boolean"}
	case reflect.Int, reflect.Int8, reflect.Int16, reflect.Int32, reflect.Int64, reflect.Uint, reflect.Uint64:
		return "number", map[string]any{"type": "integer"}
	case reflect.Float32, reflect.Float64:
		return "number", map[string]any{"type": "number"}
	case reflect.Interface:
		return "unknown", map[string]any{}
	case reflect.Slice:
		ts, schema := describe(t.Elem())
		return "Array<" + ts + "> | null", map[string]any{"anyOf": []any{map[string]any{"type": "array", "items": schema}, map[string]any{"type": "null"}}}
	case reflect.Map:
		ts, schema := describe(t.Elem())
		return "Record<string, " + ts + "> | null", map[string]any{"anyOf": []any{map[string]any{"type": "object", "additionalProperties": schema}, map[string]any{"type": "null"}}}
	case reflect.Struct:
		name, known := types[t]
		if !known {
			name = t.Name()
			types[t] = name
		}
		if _, done := declarations[name]; !done {
			declarations[name] = ""
			var lines []string
			props := map[string]any{}
			required := []string{}
			for i := 0; i < t.NumField(); i++ {
				field := t.Field(i)
				if !field.IsExported() {
					continue
				}
				tag := strings.Split(field.Tag.Get("json"), ",")
				if tag[0] == "-" {
					continue
				}
				key := tag[0]
				if key == "" {
					key = field.Name
				}
				optional := strings.Contains(field.Tag.Get("json"), ",omitempty") || strings.Contains(field.Tag.Get("json"), ",omitzero")
				ft, fs := describe(field.Type)
				props[key] = fs
				marker := ""
				if optional {
					marker = "?"
				} else {
					required = append(required, key)
				}
				lines = append(lines, fmt.Sprintf("  %q%s: %s;", key, marker, ft))
			}
			declarations[name] = "export type " + name + " = {\n" + strings.Join(lines, "\n") + "\n};\n"
			schemas[name] = map[string]any{"type": "object", "properties": props, "required": required}
		}
		return name, map[string]any{"$ref": "#/$defs/" + name}
	default:
		panic("unsupported contract kind: " + t.String())
	}
}

func main() {
	check := flag.Bool("check", false, "fail if generated contracts differ")
	flag.Parse()
	roots := []struct {
		name  string
		value any
	}{
		{"Status", app.StatusResult{}}, {"Project", model.Project{}}, {"Source", model.Source{}}, {"SyncRun", model.SyncRun{}},
		{"MemoryUnit", model.MemoryUnit{}}, {"SearchHit", model.SearchHit{}}, {"MemoryRecord", model.MemoryRecord{}},
		{"RegistryAction", registry.Action{}}, {"ConfigData", app.ConfigurationResult{}}, {"Doctor", syncer.DoctorResult{}},
		{"Credential", store.Credential{}}, {"Principal", config.PrincipalConfig{}}, {"PrincipalPolicy", store.PrincipalPolicy{}},
		{"AuditEvent", store.AuditEvent{}}, {"UploadBatch", collector.UploadBatch{}}, {"UploadReceipt", collector.UploadReceipt{}},
	}
	for _, root := range roots {
		types[reflect.TypeOf(root.value)] = root.name
	}
	for _, root := range roots {
		describe(reflect.TypeOf(root.value))
	}
	names := make([]string, 0, len(declarations))
	for name := range declarations {
		names = append(names, name)
	}
	sort.Strings(names)
	ts := "// Generated by go run ./internal/contracts. Do not edit.\n\n"
	for _, name := range names {
		ts += declarations[name] + "\n"
	}
	schema, err := json.MarshalIndent(map[string]any{"$schema": "https://json-schema.org/draft/2020-12/schema", "$defs": schemas}, "", "  ")
	if err != nil {
		panic(err)
	}
	for path, data := range map[string][]byte{"src/generated/contracts.ts": []byte(strings.TrimRight(ts, "\n") + "\n"), "docs/api.schema.json": append(schema, '\n')} {
		if *check {
			current, err := os.ReadFile(path)
			if err != nil || string(current) != string(data) {
				fmt.Fprintln(os.Stderr, "generated contract is stale:", path)
				os.Exit(1)
			}
		} else {
			if err := os.WriteFile(path, data, 0644); err != nil {
				panic(err)
			}
		}
	}
}
